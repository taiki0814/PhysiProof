/** One-time, reproducible derivation; NOT run during builds or invitations.
 * MIT upstream boundaries, pinned to a reviewed commit. Retain every polygon
 * (including islands/holes), simplify to ~20m, round to 1e-5 degrees.
 */
import { writeFile } from 'node:fs/promises';
const commit = '513fb852832c99470e16b95a30ddd68bf3469dc0';
const url = `https://raw.githubusercontent.com/piuccio/open-data-jp-prefectures-geojson/${commit}/output/prefectures.geojson`;
const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
if (!response.ok) throw new Error(`Boundary source HTTP ${response.status}`);
const source = await response.json();
if (source.features?.length !== 47) throw new Error('Expected all 47 prefectures');
const names = ['北海道','青森県','岩手県','宮城県','秋田県','山形県','福島県','茨城県','栃木県','群馬県','埼玉県','千葉県','東京都','神奈川県','新潟県','富山県','石川県','福井県','山梨県','長野県','岐阜県','静岡県','愛知県','三重県','滋賀県','京都府','大阪府','兵庫県','奈良県','和歌山県','鳥取県','島根県','岡山県','広島県','山口県','徳島県','香川県','愛媛県','高知県','福岡県','佐賀県','長崎県','熊本県','大分県','宮崎県','鹿児島県','沖縄県'];
function simplify(points) {
  const keep = new Set([0, points.length - 1]), stack = [[0, points.length - 1]];
  while (stack.length) {
    const [first, last] = stack.pop(), a = points[first], b = points[last];
    const cos = Math.cos(a[1] * Math.PI / 180), dx = (b[0] - a[0]) * cos, dy = b[1] - a[1];
    let greatest = (20 / 111_320) ** 2, split = -1;
    for (let i = first + 1; i < last; i++) {
      const x = (points[i][0] - a[0]) * cos, y = points[i][1] - a[1];
      const t = dx || dy ? Math.max(0, Math.min(1, (x * dx + y * dy) / (dx * dx + dy * dy))) : 0;
      const distance = (x - t * dx) ** 2 + (y - t * dy) ** 2;
      if (distance > greatest) { greatest = distance; split = i; }
    }
    if (split >= 0) { keep.add(split); stack.push([first, split], [split, last]); }
  }
  const result = [...keep].sort((a, b) => a - b).map(i => points[i].map(n => Number(n.toFixed(5))));
  // Tiny islands must not disappear through simplification/rounding.
  return result.length >= 4 ? result : points.map(p => p.map(n => Number(n.toFixed(5))));
}
function encodeRing(points) {
  let previousX = 0, previousY = 0, encoded = '';
  const encode = value => {
    let n = value < 0 ? -value * 2 - 1 : value * 2, text = '';
    while (n >= 32) { text += String.fromCharCode((n % 32) + 95); n = Math.floor(n / 32); }
    return text + String.fromCharCode(n + 63);
  };
  for (const [x, y] of points) {
    const nextX = Math.round(x * 100000), nextY = Math.round(y * 100000);
    encoded += encode(nextX - previousX) + encode(nextY - previousY);
    previousX = nextX; previousY = nextY;
  }
  return encoded;
}
const regions = source.features.map(feature => {
  const index = names.indexOf(feature.properties.P);
  if (index < 0) throw new Error('Unknown prefecture name in source');
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  const bounds = [Infinity, Infinity, -Infinity, -Infinity];
  for (const polygon of polygons) for (const ring of polygon) for (const [x, y] of ring) {
    bounds[0] = Math.min(bounds[0], x); bounds[1] = Math.min(bounds[1], y);
    bounds[2] = Math.max(bounds[2], x); bounds[3] = Math.max(bounds[3], y);
  }
  return { code: `JP-${String(index + 1).padStart(2, '0')}`, name: feature.properties.P,
    bounds: bounds.map(n => Number(n.toFixed(5))), polygons: polygons.map(p => p.map(r => encodeRing(simplify(r)))) };
}).sort((a,b)=>a.code.localeCompare(b.code));
if (new Set(regions.map(r=>r.code)).size !== 47) throw new Error('Duplicate/missing prefecture code');
if (regions[12].name !== '東京都' || regions[46].name !== '沖縄県') throw new Error('Unexpected prefecture ordering');
await writeFile(new URL('../packages/backend/src/data/prefectureBoundaries.ts', import.meta.url),
  `// Generated by scripts/build-prefecture-boundaries.mjs. See PREFECTURE_DATA.md for attribution.\nexport const prefectureBoundaries: {code: string; name: string; bounds: number[]; polygons: string[][]}[] = ${JSON.stringify(regions)};\n`);
console.log(`Generated 47 prefectures, ${JSON.stringify(regions).length} characters, source ${commit}`);
